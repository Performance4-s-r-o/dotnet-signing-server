/// <summary>Body of <c>POST /api/provisioning/accounts</c>.</summary>
public sealed class ProvisionAccountInput
{
    /// <summary>The integrator's id of the account: its tenant id, or <c>platform</c>.</summary>
    public string? ExternalId { get; set; }

    /// <summary>A name for the administration; optional.</summary>
    public string? Label { get; set; }

    /// <summary>The account's token, generated by the integrator (32 random bytes, base64url). Only its HMAC is kept.</summary>
    public string? ApiToken { get; set; }
}

/// <summary>Body of <c>POST /api/account/tokens/rotate</c>.</summary>
public sealed class RotateTokenInput
{
    public string? NewToken { get; set; }
}

/// <summary>Shared answers of the provisioning API (#131): <c>{ code, message }</c>, never a token.</summary>
public abstract class ProvisioningControllerBase : ControllerBase
{
    protected IStringLocalizer<SharedStrings> Localizer { get; }

    protected ProvisioningControllerBase(IStringLocalizer<SharedStrings> localizer) => Localizer = localizer;

    protected IActionResult Error(int status, string code) =>
        StatusCode(status, new { code, message = Localizer[$"Error_{code}"].Value });

    /// <summary>The API-key caller: account id, token id and kind; null for anything else (a cookie).</summary>
    protected (Guid UserId, Guid TokenId, string Kind)? ApiKeyCaller()
    {
        if (User?.Identity?.IsAuthenticated != true || User.Identity.AuthenticationType != ApiKeyAuthenticationHandler.SchemeName)
        {
            return null;
        }
        var userClaim = User.FindFirst(ClaimTypes.NameIdentifier)?.Value;
        var tokenId = SessionClaims.TokenIdOf(User);
        var kind = User.FindFirst(SessionClaims.TokenKind)?.Value;
        if (!Guid.TryParse(userClaim, out var userId) || tokenId is not Guid id || kind == null) return null;
        return (userId, id, kind);
    }

    protected IActionResult Limited(int retryAfterSeconds)
    {
        Response.Headers.RetryAfter = retryAfterSeconds.ToString(System.Globalization.CultureInfo.InvariantCulture);
        return Error(StatusCodes.Status429TooManyRequests, "PROVISIONING_LIMIT");
    }
}

/// <summary>
/// The integrator's provisioning API (#131), for its provisioning token only (the gate refuses
/// every other token, and this token everywhere else).
/// </summary>
[Route("api/provisioning")]
public sealed class ProvisioningApiController : ProvisioningControllerBase
{
    public const int MaxListLimit = 1000;

    private readonly AccountProvisioner _provisioner;

    public ProvisioningApiController(AccountProvisioner provisioner, IStringLocalizer<SharedStrings> localizer)
        : base(localizer)
    {
        _provisioner = provisioner;
    }

    private ProvisioningCaller? Caller()
    {
        var caller = ApiKeyCaller();
        if (caller is not { Kind: SessionClaims.ProvisioningTokenKind } c) return null;
        return new ProvisioningCaller(c.UserId, c.TokenId, Middleware.ClientIp.AddressOf(HttpContext)?.ToString());
    }

    private static object Describe(User account) => new
    {
        accountId = account.Id,
        externalId = account.ExternalId,
        label = account.Label,
        createdAt = account.CreatedAt,
        inherits = new { enterprise = account.EffectiveEnterprise, sealAllowed = account.EffectiveSealAllowed },
    };

    [HttpPost("accounts")]
    public async Task<IActionResult> Create([FromBody] ProvisionAccountInput? input)
    {
        if (Caller() is not { } caller) return Error(StatusCodes.Status403Forbidden, BrowserTokenScope.ScopeErrorCode);

        var result = await _provisioner.ProvisionAsync(caller, input?.ExternalId, input?.Label, input?.ApiToken, CancellationToken.None);
        return result.Outcome switch
        {
            ProvisionOutcome.Created => StatusCode(StatusCodes.Status201Created, Describe(result.Account!)),
            ProvisionOutcome.Replayed => Ok(Describe(result.Account!)),
            ProvisionOutcome.Conflict => Error(StatusCodes.Status409Conflict, "ACCOUNT_EXISTS"),
            ProvisionOutcome.ParentNotEnterprise => Error(StatusCodes.Status409Conflict, "PARENT_NOT_ENTERPRISE"),
            ProvisionOutcome.Limited => Limited(result.RetryAfterSeconds),
            ProvisionOutcome.InvalidExternalId => Error(StatusCodes.Status400BadRequest, "EXTERNAL_ID_INVALID"),
            ProvisionOutcome.InvalidLabel => Error(StatusCodes.Status400BadRequest, "LABEL_INVALID"),
            ProvisionOutcome.WeakToken => Error(StatusCodes.Status400BadRequest, "TOKEN_WEAK"),
            _ => Error(StatusCodes.Status403Forbidden, BrowserTokenScope.ScopeErrorCode),
        };
    }

    [HttpGet("accounts")]
    public async Task<IActionResult> List([FromQuery] string? externalId, [FromQuery] int? limit)
    {
        if (Caller() is not { } caller) return Error(StatusCodes.Status403Forbidden, BrowserTokenScope.ScopeErrorCode);
        if (await _provisioner.IsRateLimitedAsync("provision", caller.TokenId, HttpContext.RequestAborted))
        {
            await _provisioner.RecordListRefusalAsync(caller, AccountProvisioningOutcomes.RefusedLimit, CancellationToken.None);
            return Limited(60);
        }
        if (externalId != null && !AccountProvisioner.IsValidExternalId(externalId))
        {
            await _provisioner.RecordListRefusalAsync(caller, AccountProvisioningOutcomes.Invalid, CancellationToken.None);
            return Error(StatusCodes.Status400BadRequest, "EXTERNAL_ID_INVALID");
        }

        var take = Math.Clamp(limit ?? MaxListLimit, 1, MaxListLimit);
        var rows = await _provisioner.ListAsync(caller, externalId, take, HttpContext.RequestAborted);
        return Ok(new
        {
            accounts = rows.Select(u => new
            {
                accountId = u.Id,
                externalId = u.ExternalId,
                label = u.Label,
                createdAt = u.CreatedAt,
                isActive = u.IsActive && u.ErasedAt == null,
                erasedAt = u.ErasedAt,
            }),
        });
    }
}

/// <summary>
/// What a provisioned account does with its own token (#131): rotate it in two steps and delete
/// itself when its tenant closes. Ordinary accounts get 403 <c>TOKEN_SCOPE</c>: their tokens are
/// managed in the web UI, behind a recent sign-in.
/// </summary>
[Route("api/account")]
public sealed class ProvisionedAccountApiController : ProvisioningControllerBase
{
    private readonly ApplicationDbContext _db;
    private readonly AccountProvisioner _provisioner;
    private readonly IApiAuthService _apiAuth;
    private readonly AccountErasureService _erasure;
    private readonly IOptions<LimitsOptions> _limits;
    private readonly ILogger<ProvisionedAccountApiController> _logger;

    public ProvisionedAccountApiController(
        ApplicationDbContext db,
        AccountProvisioner provisioner,
        IApiAuthService apiAuth,
        AccountErasureService erasure,
        IOptions<LimitsOptions> limits,
        IStringLocalizer<SharedStrings> localizer,
        ILogger<ProvisionedAccountApiController> logger)
        : base(localizer)
    {
        _db = db;
        _provisioner = provisioner;
        _apiAuth = apiAuth;
        _erasure = erasure;
        _limits = limits;
        _logger = logger;
    }

    /// <summary>The calling provisioned account and its token; null for any other caller.</summary>
    private async Task<(User Account, Guid TokenId)?> ProvisionedCallerAsync()
    {
        if (ApiKeyCaller() is not { Kind: SessionClaims.ServerTokenKind } caller) return null;
        var account = await _db.Users.Include(u => u.Parent).FirstOrDefaultAsync(u => u.Id == caller.UserId);
        if (account is not { ParentUserId: not null } || !account.EffectiveActive || account.ErasedAt != null) return null;
        return (account, caller.TokenId);
    }

    /// <summary>Adds a token the integrator generated; the current one keeps working until <c>revoke-others</c>.</summary>
    [HttpPost("tokens/rotate")]
    public async Task<IActionResult> Rotate([FromBody] RotateTokenInput? input)
    {
        if (await ProvisionedCallerAsync() is not { } caller) return Error(StatusCodes.Status403Forbidden, BrowserTokenScope.ScopeErrorCode);
        if (await _provisioner.IsRateLimitedAsync("rotate", caller.Account.Id, HttpContext.RequestAborted)) return Limited(60);

        var value = input?.NewToken;
        if (string.IsNullOrWhiteSpace(value) || PortalBootstrap.Validate(value, "newToken").Count > 0)
        {
            return Error(StatusCodes.Status400BadRequest, "TOKEN_WEAK");
        }

        var hash = _provisioner.HashOf(value);
        var now = DateTimeOffset.UtcNow;
        var active = await _db.ApiTokens
            .Where(t => t.UserId == caller.Account.Id && t.RevokedAt == null && (t.ExpiresAt == null || t.ExpiresAt > now))
            .ToListAsync();
        var same = active.FirstOrDefault(t => CryptographicOperations.FixedTimeEquals(t.TokenHash, hash));
        if (same != null) return Ok(new { tokenId = same.Id });

        // Revoked here or used anywhere else: a value never gets a second meaning.
        if (await _db.ApiTokens.AnyAsync(t => t.TokenHash == hash)) return Error(StatusCodes.Status409Conflict, "TOKEN_IN_USE");

        var max = _limits.Value.MaxApiTokensPerUser;
        if (max > 0 && active.Count >= max) return Error(StatusCodes.Status409Conflict, "TOO_MANY_API_TOKENS");

        var token = new ApiToken
        {
            UserId = caller.Account.Id,
            Label = AccountProvisioner.TokenLabel,
            TokenHash = hash,
            TokenPrefix = null,
            IsBrowserToken = false,
            IsProvisioningToken = false,
        };
        _db.ApiTokens.Add(token);
        await _db.SaveChangesAsync();
        _logger.LogInformation("Provisioned account {AccountId} added token {TokenId}", caller.Account.Id, token.Id);
        return Ok(new { tokenId = token.Id });
    }

    /// <summary>Revokes every other active token of the account; called with the new one.</summary>
    [HttpPost("tokens/revoke-others")]
    public async Task<IActionResult> RevokeOthers()
    {
        if (await ProvisionedCallerAsync() is not { } caller) return Error(StatusCodes.Status403Forbidden, BrowserTokenScope.ScopeErrorCode);

        var now = DateTimeOffset.UtcNow;
        var others = await _db.ApiTokens
            .Where(t => t.UserId == caller.Account.Id && t.RevokedAt == null && t.Id != caller.TokenId)
            .ToListAsync();
        foreach (var token in others) token.RevokedAt = now;
        await _db.SaveChangesAsync();
        foreach (var token in others) _apiAuth.InvalidateTokenCache(token.Id);
        _logger.LogInformation("Provisioned account {AccountId} revoked {Count} other token(s)", caller.Account.Id, others.Count);
        return Ok(new { tokenId = caller.TokenId, revoked = others.Count });
    }

    /// <summary>Erases the account (its tenant closed). Its tokens go with it, so a repeat gets 401.</summary>
    [HttpDelete("")]
    public async Task<IActionResult> Delete()
    {
        if (await ProvisionedCallerAsync() is not { } caller) return Error(StatusCodes.Status403Forbidden, BrowserTokenScope.ScopeErrorCode);

        // Not RequestAborted: a dropped connection must not stop the erasure halfway.
        var result = await _erasure.DeleteProvisionedAccountAsync(caller.Account.Id, CancellationToken.None);
        return result.Status switch
        {
            AccountErasureStatus.Erased => Ok(new { status = "erased" }),
            AccountErasureStatus.AlreadyErased or AccountErasureStatus.NotFound => Ok(new { status = "already_erased" }),
            _ => Error(StatusCodes.Status409Conflict, "ACCOUNT_DELETE_REFUSED"),
        };
    }
}
